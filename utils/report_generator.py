"""
PDF Report Generator for Breast Cancer Predictions
"""
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.enums import TA_CENTER, TA_LEFT
from datetime import datetime


def generate_pdf_report(prediction_data, output_path):
    """
    Generate a PDF report for breast cancer prediction
    
    Args:
        prediction_data: Dict containing prediction, probability, features, etc.
        output_path: Path where PDF should be saved
    
    Returns:
        str: Path to generated PDF
    """
    try:
        # Create PDF
        doc = SimpleDocTemplate(output_path, pagesize=letter)
        story = []
        styles = getSampleStyleSheet()
        
        # Custom styles
        title_style = ParagraphStyle(
            'CustomTitle',
            parent=styles['Heading1'],
            fontSize=24,
            textColor=colors.HexColor('#2C3E50'),
            spaceAfter=30,
            alignment=TA_CENTER
        )
        
        heading_style = ParagraphStyle(
            'CustomHeading',
            parent=styles['Heading2'],
            fontSize=16,
            textColor=colors.HexColor('#34495E'),
            spaceAfter=12,
            spaceBefore=12
        )
        
        # Title
        title = Paragraph("Breast Cancer Prediction Report", title_style)
        story.append(title)
        story.append(Spacer(1, 0.3*inch))
        
        # Prediction Result
        prediction = prediction_data['prediction']
        probability = prediction_data['probability']
        confidence = prediction_data['confidence']
        
        diagnosis = 'MALIGNANT' if prediction == 1 else 'BENIGN'
        risk_color = colors.red if prediction == 1 else colors.green
        
        result_text = f"""
        <para align=center>
        <font size=18 color={'red' if prediction == 1 else 'green'}>
        <b>Diagnosis: {diagnosis}</b>
        </font>
        <br/>
        <font size=14>
        Confidence: {confidence*100:.1f}%
        </font>
        </para>
        """
        
        story.append(Paragraph(result_text, styles['Normal']))
        story.append(Spacer(1, 0.5*inch))
        
        # Metadata
        story.append(Paragraph("Report Information", heading_style))
        
        metadata = [
            ['Report Date:', prediction_data.get('timestamp', datetime.now().strftime('%Y-%m-%d %H:%M:%S'))],
            ['Model Used:', 'RLT Forest (Randomized Learning Trees)'],
            ['Risk Level:', 'High' if prediction == 1 else 'Low']
        ]
        
        metadata_table = Table(metadata, colWidths=[2*inch, 4*inch])
        metadata_table.setStyle(TableStyle([
            ('ALIGN', (0, 0), (-1, -1), 'LEFT'),
            ('FONTNAME', (0, 0), (0, -1), 'Helvetica-Bold'),
            ('FONTSIZE', (0, 0), (-1, -1), 10),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
        ]))
        
        story.append(metadata_table)
        story.append(Spacer(1, 0.3*inch))
        
        # Disclaimer
        story.append(Paragraph("Important Notice", heading_style))
        disclaimer = """
        <para align=left>
        This report is generated by a machine learning model and is intended for 
        educational and research purposes only. It should NOT be used as a substitute 
        for professional medical advice, diagnosis, or treatment. Always consult with 
        qualified healthcare providers for medical decisions.
        </para>
        """
        story.append(Paragraph(disclaimer, styles['Normal']))
        
        # Build PDF
        doc.build(story)
        
        return output_path
        
    except Exception as e:
        print(f"Error generating PDF: {e}")
        raise
